// Generates docs/generated/catalog.md (for people and steering) and catalog.json (for comparisons).

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import type { Context, Value } from "./types.ts";

export const CATALOG_MD = "docs/generated/catalog.md";
export const CATALOG_JSON = "docs/generated/catalog.json";
export const MAX_LINE = 120;

export type Permissions = { reads: string[]; writes: string[]; storage: string[] };

export type CatalogStep = {
  name: string;
  class: string | null;
  file: string;
  input: string | null;
  output: string | null;
  permissions: Permissions | null;
  errors: string[] | null;
  usedBy: string[];
};

export type CatalogStrip = { name: string; file: string; steps: string[]; budget: Permissions | null };

export type Catalog = { version: 1; steps: CatalogStep[]; strips: CatalogStrip[] };

const oneLine = (s: string): string => s.replace(/\s+/g, " ").trim();

function text(v: Value | undefined): string | null {
  if (!v) return null;
  if (v.kind === "string") return JSON.stringify(v.value);
  if (v.kind === "strings") return `[${v.value.map((x) => JSON.stringify(x)).join(", ")}]`;
  if (v.kind === "identifiers") return `[${v.value.join(", ")}]`;
  if (v.kind === "expr") return oneLine(v.text);
  return "{...}";
}

function perms(v: Value | undefined): Permissions | null {
  if (!v || v.kind !== "object") return null;
  const out: Permissions = { reads: [], writes: [], storage: [] };
  for (const k of ["reads", "writes", "storage"] as const) {
    const inner = v.props[k];
    if (inner === undefined) continue;
    if (inner.kind !== "strings") return null;
    out[k] = [...inner.value].sort();
  }
  return out;
}

const byName = <T extends { name: string }>(a: T, b: T): number => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0);

/** Builds the catalog from discovered steps and strips with literal names. Stable order. */
export function buildCatalog(ctx: Pick<Context, "steps" | "strips">): Catalog {
  const usedBy = new Map<string, Set<string>>();
  const strips: CatalogStrip[] = [];
  for (const s of ctx.strips) {
    if (s.name === null) continue;
    const stepNames = s.stepRefs.map((r) => r.step?.name ?? `?${r.text}`);
    for (const n of stepNames) {
      const set = usedBy.get(n) ?? new Set<string>();
      set.add(s.name);
      usedBy.set(n, set);
    }
    strips.push({ name: s.name, file: s.file, steps: stepNames, budget: perms(s.props.budget) });
  }
  const steps: CatalogStep[] = [];
  for (const s of ctx.steps) {
    if (s.name === null) continue;
    const errs = s.props.errors;
    const cls = s.props.class;
    steps.push({
      name: s.name,
      class: cls && cls.kind === "string" ? cls.value : null,
      file: s.file,
      input: text(s.props.input),
      output: text(s.props.output),
      permissions: perms(s.props.permissions),
      errors: errs && errs.kind === "strings" ? [...errs.value].sort() : null,
      usedBy: [...(usedBy.get(s.name) ?? [])].sort(),
    });
  }
  return { version: 1, steps: steps.sort(byName), strips: strips.sort(byName) };
}

export function catalogJson(c: Catalog): string {
  return JSON.stringify(c, null, 2) + "\n";
}

const list = (xs: string[] | undefined | null): string => (!xs || xs.length === 0 ? "-" : xs.join(","));

function cap(line: string): string {
  return line.length <= MAX_LINE ? line : `${line.slice(0, MAX_LINE - 3)}...`;
}

export function catalogMd(c: Catalog): string {
  const out: string[] = [
    "# Catalog",
    "",
    "Generated by `pnpm conformance --write-catalog`. Do not edit. Full detail: `catalog.json`.",
    "Step line: name (class) | in | out | r=reads w=writes s=storage | used by.",
    "",
    "## Steps",
    "",
  ];
  if (c.steps.length === 0) out.push("None.");
  for (const s of c.steps) {
    const p = s.permissions;
    const pr = p ? `r=${list(p.reads)} w=${list(p.writes)} s=${list(p.storage)}` : "permissions=?";
    out.push(cap(`- ${s.name} (${s.class ?? "?"}) | in ${s.input ?? "?"} | out ${s.output ?? "?"} | ${pr} | used by ${list(s.usedBy)}`));
  }
  out.push("", "## Strips", "");
  if (c.strips.length === 0) out.push("None.");
  for (const s of c.strips) {
    const b = s.budget;
    const br = b ? `r=${list(b.reads)} w=${list(b.writes)} s=${list(b.storage)}` : "budget=?";
    out.push(cap(`- ${s.name} | steps ${list(s.steps)} | ${br}`));
  }
  return out.join("\n") + "\n";
}

export function writeCatalog(root: string, c: Catalog): void {
  for (const [rel, body] of [
    [CATALOG_MD, catalogMd(c)],
    [CATALOG_JSON, catalogJson(c)],
  ] as const) {
    mkdirSync(dirname(join(root, rel)), { recursive: true });
    writeFileSync(join(root, rel), body);
  }
}

export function parseCatalog(text: string | null): Catalog | null {
  if (text === null) return null;
  try {
    const c = JSON.parse(text) as Catalog;
    return c && c.version === 1 && Array.isArray(c.steps) ? c : null;
  } catch {
    return null;
  }
}
